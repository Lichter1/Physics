// Assembles the Observatorium. No dependencies:  node build.mjs
//   dist/index.html + dist/data/   the page as published (data fetched beside it, loaded per chapter)
//   observatorium.html             one stand-alone file with every dataset inlined: open it from disk, offline
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, 'src', p), 'utf8');
export const SCRIPTS = ['core', 'astro', 'catalog', 'chart', 'sky', 'instruments', 'explainers', 'missions', 'lectures', 'lecture', 'logbook', 'tour', 'main'];

const head = [
  '<title>Observatorium</title>',
  '<meta name="claude:viewport-fit-sides" content="cover">',
  '<meta name="description" content="Learn General Astronomy 1 by retracing its discoveries with real data: Gaia, Hipparcos, OGLE, Kepler, SDSS, SPARC and more.">',
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans+Condensed:wght@400;500;600&family=Spectral:ital,wght@0,400;0,500;0,600;1,400&display=swap">',
  '<style>\n' + read('style.css') + '</style>',
  // MathJax typesets the lectures' equations (SVG output: no web fonts needed)
  '<script>window.MathJax = { tex: { inlineMath: [["\\\\(", "\\\\)"]], displayMath: [["\\\\[", "\\\\]"]] }, svg: { fontCache: "global" }, ' +
  'startup: { typeset: false, ready: function () { MathJax.startup.defaultReady(); MathJax.startup.promise.then(function () { if (window.OBS && OBS.mathReady) OBS.mathReady(); }); } } };</script>',
  '<script defer src="https://cdn.jsdelivr.net/npm/mathjax@3.2.2/es5/tex-svg.js"></script>'
].join('\n');
const code = SCRIPTS.map((s) => read(`js/${s}.js`)).join('\n');
if (code.includes('</script')) throw new Error('a source file contains "</script"');
const body = read('page.html') + '\n<script>\n' + code + '</script>\n';

// 1. the published page and its data
const dist = join(root, 'dist');
rmSync(join(dist, 'data'), { recursive: true, force: true });  // keep dist/ itself, so a preview server running in it survives a rebuild
mkdirSync(join(dist, 'data'), { recursive: true });
writeFileSync(join(dist, 'index.html'), head + '\n' + body);
// a full document around the same page, for previewing dist/ on a local server
writeFileSync(join(dist, 'preview.html'), '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' + head + '\n<style>body{margin:0}</style>\n</head>\n<body>\n' + body + '</body>\n</html>\n');
const files = readdirSync(join(root, 'data')).filter((f) => /\.(csv|json)$/.test(f));
files.forEach((f) => copyFileSync(join(root, 'data', f), join(dist, 'data', f)));
const images = readdirSync(join(root, 'data', 'img')).filter((f) => /\.jpg$/.test(f))
  .concat(readdirSync(join(root, 'data', 'img', 'lec')).filter((f) => /\.jpg$/.test(f)).map((f) => 'lec/' + f));
mkdirSync(join(dist, 'data', 'img', 'lec'), { recursive: true });
images.forEach((f) => copyFileSync(join(root, 'data', 'img', f), join(dist, 'data', 'img', f)));

// 2. the stand-alone file
const inline = {};
files.forEach((f) => { inline[f] = readFileSync(join(root, 'data', f), 'utf8'); });
images.forEach((f) => { inline['img/' + f] = 'data:image/jpeg;base64,' + readFileSync(join(root, 'data', 'img', f)).toString('base64'); });
const blob = JSON.stringify(inline).replace(/<\//g, '<\\/');
writeFileSync(join(root, 'observatorium.html'),
  '<!doctype html>\n<!-- Generated by build.mjs from src/ and data/. Edit those, not this file. -->\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' + head +
  '\n<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}</style>\n</head>\n<body>\n' +
  '<script>window.OBS_INLINE = ' + blob + ';</script>\n' + body + '</body>\n</html>\n');
const mb = (n) => (n / 1e6).toFixed(2) + ' MB';
console.log('built dist/index.html (' + mb(Buffer.byteLength(head + body)) + ') with ' + files.length + ' data files and ' + images.length + ' photographs, and observatorium.html (' + mb(Buffer.byteLength(blob)) + ' of data inlined)');
