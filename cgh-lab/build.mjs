// Assembles the lab into single files. No dependencies:  node build.mjs
//   index.html              stand-alone page: open it in a browser, or host it anywhere
//   dist/cgh-lab.html       the same page as a fragment (no <html>/<head>), for hosts that wrap it
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, 'src', p), 'utf8');
const scripts = ['physics', 'qcore', 'geo', 'shaders', 'app', 'wave', 'world', 'probe', 'labs', 'missions', 'quiz', 'main'];

const head = [
  '<title>cGħ World</title>',
  '<meta name="claude:viewport-fit-sides" content="cover">',
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&family=STIX+Two+Text:ital,wght@0,500;0,600;1,500;1,600&display=swap">',
  '<style>\n' + read('style.css') + '</style>'
].join('\n');
const body = read('page.html') +
  '\n<script>\n' + scripts.map((s) => read(`js/${s}.js`)).join('\n') + '</script>\n';

if (body.split('</script>').length !== 2) throw new Error('a source file contains "</script>"');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'cgh-lab.html'), head + '\n' + body);
writeFileSync(join(root, 'index.html'),
  '<!doctype html>\n<!-- Generated by build.mjs from src/. Edit the sources, not this file. -->\n' +
  '<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
  head + '\n</head>\n<body>\n' + body + '</body>\n</html>\n');
console.log('built index.html and dist/cgh-lab.html');
